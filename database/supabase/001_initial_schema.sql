-- SIAM PostgreSQL schema for Supabase.
-- Execute this migration in the Supabase SQL Editor on a new/empty project.
-- Do not run against production data before taking a backup and reviewing the migration plan.

CREATE TABLE IF NOT EXISTS app_user (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    login VARCHAR(120) NOT NULL UNIQUE,
    registration VARCHAR(20) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    user_type VARCHAR(20) NOT NULL CHECK (user_type IN ('ADMIN', 'FISCAL')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS gas_station (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cnpj VARCHAR(18) NOT NULL UNIQUE,
    corporate_name VARCHAR(150) NOT NULL,
    address VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS gas_pump (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gas_station_id INTEGER NOT NULL REFERENCES gas_station(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    serial_number VARCHAR(100) NOT NULL,
    model VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS fiscalization (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES app_user(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    gas_pump_id INTEGER NOT NULL REFERENCES gas_pump(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    fiscalization_date TIMESTAMP NOT NULL,
    irregularity_type VARCHAR(100),
    measurement_error NUMERIC(10, 2),
    audit_status VARCHAR(50) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    archived_at TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS next_steps (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fiscalization_id INTEGER NOT NULL REFERENCES fiscalization(id) ON DELETE CASCADE ON UPDATE CASCADE,
    action_description TEXT NOT NULL,
    concluded BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS photo_evidence (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fiscalization_id INTEGER NOT NULL REFERENCES fiscalization(id) ON DELETE CASCADE ON UPDATE CASCADE,
    path_archive VARCHAR(255) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_gas_pump_station_id ON gas_pump(gas_station_id);
CREATE INDEX IF NOT EXISTS idx_fiscalization_user_id ON fiscalization(user_id);
CREATE INDEX IF NOT EXISTS idx_fiscalization_pump_id ON fiscalization(gas_pump_id);
CREATE INDEX IF NOT EXISTS idx_fiscalization_date ON fiscalization(fiscalization_date);
CREATE INDEX IF NOT EXISTS idx_fiscalization_status ON fiscalization(audit_status);

